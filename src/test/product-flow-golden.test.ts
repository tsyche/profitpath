import { readFileSync } from 'node:fs';
import { afterEach, describe, expect, it } from 'vitest';
import { calc } from '../calculations/index';
import { setRangeCase, type RangeCase } from '../calculations/rangeCase';
import { hybridFixture } from '../../assets/prototypes/fixtures';
import type { Mode, PoolUtilization } from '../types';

interface GoldenResult {
  mode: Mode;
  activeCase: RangeCase;
  revenue: number;
  income: number;
  capacityPct: number;
  takeHome: number;
  yearOneCashFlow: number;
  poolUtilization: PoolUtilization[];
}

// Captured through the unmodified application in Phase 0, not regenerated by this test.
const golden: GoldenResult[] = JSON.parse(readFileSync(
  'docs/ledger/product-flow-baseline/2026-10-28/golden.json', 'utf8'
));

afterEach(() => setRangeCase('base'));

describe('product-flow unchanged-model compatibility', () => {
  for (const expected of golden) {
    it(`preserves the hybrid ${expected.mode} model in the ${expected.activeCase} case`, () => {
      const model = hybridFixture();
      model.mode = expected.mode;
      setRangeCase(expected.activeCase);
      const actual = calc(model, { enableCache: false });
      for (const key of ['revenue', 'income', 'capacityPct', 'takeHome', 'yearOneCashFlow'] as const) {
        expect(actual[key], key).toBeCloseTo(expected[key], 8);
      }
      expect(actual.poolUtilization.map(pool => pool.id)).toEqual(expected.poolUtilization.map(pool => pool.id));
      actual.poolUtilization.forEach((pool, index) => {
        expect(pool.pct, pool.name).toBeCloseTo(expected.poolUtilization[index].pct, 8);
      });
    });
  }
});
